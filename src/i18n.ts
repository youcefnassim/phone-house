const fr: Record<MessageKey, string> = { ...coreFr, ...moduleFr };
const ar: Record<MessageKey, string> = { ...coreAr, ...moduleAr };

export const dictionaries: Record<Language, Record<MessageKey, string>> = {
  en,
  "fr-DZ": fr,
  "ar-DZ": ar,
};

export function translate(
  lang: Language,
  key: MessageKey,
  params?: Record<string, string>,
): string {
  let text = dictionaries[lang][key] ?? en[key] ?? key;
  if (params)
    for (const [name, value] of Object.entries(params)) text = text.replaceAll(`{${name}}`, value);
  return text;
}
