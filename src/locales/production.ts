export function productionText(lang: string, key: string, params?: Record<string, string>): string {
  const extra = stockCountText(lang);
  const op: Record<string, string> = {
    "supplier.cost": extra.cost,
    "supplier.payment": extra.payment,
    "count.open": extra.open,
    "count.entry": extra.save,
    "count.submit": extra.submit,
    "stock.adjust": extra.adjust,
    "stock.review": extra.review,
    "transfer.resolve": extra.resolve,
    "transfer.cancel": extra.cancel,
  };
  if (key.startsWith("op.") && op[key.slice(3)]) return op[key.slice(3)] ?? key;
  if (
    key.startsWith("f.") &&
    ![
      "amount",
      "note",
      "itemId",
      "transferId",
      "shiftId",
      "bankMethod",
      "phoneId",
      "supplierId",
    ].includes(key.slice(2)) &&
    key.slice(2) in extra
  )
    return extra[key.slice(2) as keyof typeof extra];
  if (key === "c.phone") return extra.phone;
  if (key === "op.transfer.receive") return extra.receive;
  const dict = (lang === "ar-DZ" ? ar : lang === "en" ? en : fr) as Record<string, string>;
  let value = dict[key] ?? (en as Record<string, string>)[key] ?? key;
  for (const [k, v] of Object.entries(params ?? {})) value = value.replace(`{${k}}`, v);
  return value;
}
