export function scopedRows(rows: RecordRow[], scope: Scope) {
  return rows.filter((item) => scope === "ALL" || item.store === scope);
}
export const demoAdapter: DataContract = {
  mode: "demo",
  async list(area, scope) {
    return scopedRows(
      area === "phones"
        ? stock.filter((i) => i.kind === "phone")
        : area === "accessories"
          ? stock.filter((i) => i.kind === "accessory")
          : (demoAreas[area] ?? []),
      scope,
    );
  },
};
