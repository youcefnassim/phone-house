// LOCAL DEV ONLY: writes .dev.vars (git-ignored) with a fresh ES256 signing key and pepper for
// `wrangler dev --env dev`. Never use these values anywhere else; staging/prod secrets are created with
// `wrangler secret put` only after the owner's "go" for that environment.
// Usage: bun scripts/auth-dev-secrets.ts            (refuses to overwrite an existing .dev.vars)
import { existsSync, writeFileSync } from "node:fs";
import { exportJWK, generateKeyPair } from "jose";

if (existsSync(".dev.vars")) {
  console.error(".dev.vars already exists; delete it first if you really want new local secrets.");
  process.exit(1);
}
const { privateKey } = await generateKeyPair("ES256", { extractable: true });
const jwk = {
  ...(await exportJWK(privateKey)),
  kid: `dev-${new Date().toISOString().slice(0, 10)}`,
};
const pepper = btoa(String.fromCharCode(...crypto.getRandomValues(new Uint8Array(32))));
writeFileSync(
  ".dev.vars",
  [
    "# LOCAL DEV ONLY - generated by scripts/auth-dev-secrets.ts - never commit",
    `AUTH_SIGNING_JWK='${JSON.stringify(jwk)}'`,
    `AUTH_PEPPERS='${JSON.stringify({ dev1: pepper })}'`,
    "AUTH_PEPPER_ID=dev1",
    "",
  ].join("\n"),
  { mode: 0o600 },
);
console.log(
  "Wrote .dev.vars (mode 600). Bootstrap a local owner with scripts/auth-break-glass.ts --env dev.",
);
